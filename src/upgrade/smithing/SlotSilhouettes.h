/// Draws a silhouette at (x, y) with `alpha` (vanilla: dark grey on the slot).
inline void draw(::abp::client::ui::Painter& p, Art const& art, float x, float y, float alpha) {
    static std::vector<std::string_view> const palette{"#=373737"};
    Art colored{art.rows, palette};
    p.pixels(colored, x, y, 1, ::abp::client::ui::Painter::Layer::Background, alpha);
}

/// SC CyclingSlotBackground: a new icon every 30 ticks (1.5 s), cross-faded over 4 ticks.
inline void drawCycle(::abp::client::ui::Painter& p, std::vector<Art const*> const& cycle, float x, float y, double time) {
    if (cycle.empty()) return;
    constexpr double kPeriod = 1.5, kFade = 0.2;
    auto   n     = static_cast<long long>(time / kPeriod);
    auto   cur   = cycle[static_cast<std::size_t>(n % static_cast<long long>(cycle.size()))];
    double phase = time - static_cast<double>(n) * kPeriod;
    if (cycle.size() > 1 && phase < kFade) {
        auto  prev = cycle[static_cast<std::size_t>((n + static_cast<long long>(cycle.size()) - 1) % static_cast<long long>(cycle.size()))];
        float a    = static_cast<float>(phase / kFade);
        draw(p, *prev, x, y, 1 - a);
        draw(p, *cur, x, y, a);
        return;
    }
    draw(p, *cur, x, y, 1);
}

