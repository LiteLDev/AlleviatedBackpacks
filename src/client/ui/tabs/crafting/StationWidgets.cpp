/// A copy of `art` keeping only rows [from, to) and columns [0, cols).
PixelArt cropped(PixelArt const& art, int fromRow, int toRow, int cols) {
    PixelArt out;
    out.palette = art.palette;
    for (int r = 0; r < art.height(); ++r) {
        auto line = art.rows[static_cast<std::size_t>(r)];
        if (r < fromRow || r >= toRow) {
            out.rows.push_back(std::string_view{});
            continue;
        }
        out.rows.push_back(line.substr(0, static_cast<std::size_t>(std::clamp(cols, 0, static_cast<int>(line.size())))));
    }
    return out;
}

// ---- open-tab reporting ---------------------------------------------------------------------------------
// Closes are queued in trivially destructible storage (a widget can be destroyed at any time,
// even during static destruction) and sent from a UI layer on the next frame.
struct PendingClose {
    char uuid[64];
    int  slot;
};
PendingClose gPending[16];
int          gPendingCount = 0;
bool         gAlive        = false; ///< the flush layer has run at least once (client running)

void flushPending() {
    for (int i = 0; i < gPendingCount; ++i) {
        net::sendScreenAction({
            {"action", "tab"},
            {"slot",   gPending[i].slot},
            {"data",   {{"tabOpen", false}, {"uuid", std::string(gPending[i].uuid)}}}
        });
    }
    gPendingCount = 0;
}

/// Invisible widget whose destruction means "this tab's widgets were cleared".
class TabOpenSentinel final : public Widget {
public:
    TabOpenSentinel(std::string const& uuid, int slot) : mSlot(slot) {
        std::size_t n = std::min(uuid.size(), sizeof(mUuid) - 1);
        std::memcpy(mUuid, uuid.data(), n);
        mUuid[n] = '\0';
        visible  = false;
    }
    ~TabOpenSentinel() override {
        if (!gAlive || gPendingCount >= static_cast<int>(std::size(gPending))) return;
        std::memcpy(gPending[gPendingCount].uuid, mUuid, sizeof(mUuid));
        gPending[gPendingCount].slot = mSlot;
        ++gPendingCount;
    }
    void render(Painter&, float, float, double) override {}

private:
    char mUuid[64]{};
    int  mSlot;
};

/// Sends queued tab-close reports once per frame (never visible).
class FlushLayer final : public IUiLayer {
public:
    [[nodiscard]] char const* name() const override { return "abp.station.flush"; }
    [[nodiscard]] int         zOrder() const override { return 0; }
    [[nodiscard]] bool        visible(FrameInfo const&) const override {
        gAlive = true;
        if (gPendingCount > 0) flushPending();
        return false;
    }
    void render(Painter&, FrameInfo const&) override {}
};
FlushLayer gFlushLayer;
ABP_REGISTER_UI_LAYER(gFlushLayer);

