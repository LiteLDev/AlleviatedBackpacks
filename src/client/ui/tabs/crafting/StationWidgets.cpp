ItemStack const* cursorItem() {
    auto* player = currentPlayer();
    if (!player) return nullptr;
    auto const& c = player->mPlayerUIContainer->getItem(0);
    return c.isNull() ? nullptr : &c;
}

ItemStack stackFromJson(nlohmann::json const& j) {
    if (!j.is_object()) return {};
    try {
        auto d = core::ItemStackData::fromJson(j);
        if (d.empty()) return {};
        return game::ItemConv::toStack(d, std::clamp(d.count, 1, 255));
    } catch (...) {
        return {};
    }
}

void drawCount(Painter& p, long long count, float x, float y) {
    if (count <= 1) return;
    auto c = Color::rgb(0xFFFFFF);
    if (count <= 99) {
        auto s = std::to_string(count);
        p.text(s, x + 19 - 2 - p.textWidth(s), y + 6 + 3, c, true);
        return;
    }
    auto  s     = core::screen::abbreviateCount(count);
    float w     = p.textWidth(s);
    float scale = std::min(1.f, 16.f / std::max(1.f, w));
    p.text(s, x + 19 - 2 - w * scale, y + 6 + 3 + (1 / (scale * scale) - 1), c, true, scale);
}

std::vector<TooltipLine> lines(std::string const& text, std::uint32_t rgb) {
    std::vector<TooltipLine> out;
    std::size_t              start = 0;
    while (true) {
        auto nl = text.find('\n', start);
        out.push_back({text.substr(start, nl == std::string::npos ? std::string::npos : nl - start), rgb});
        if (nl == std::string::npos) break;
        start = nl + 1;
    }
    return out;
}

void icon(Painter& p, Icon which, float x, float y) { p.pixels(artOf(which), x, y, 1, L::Foreground); }

void iconBottomUp(Painter& p, Icon which, float x, float y, float progress, float height) {
    if (progress <= 0) return; // SC ProgressBar draws nothing at 0
    auto const& art = artOf(which);
    int         off = static_cast<int>(height * progress);
    p.pixels(cropped(art, off, art.height(), art.width()), x, y, 1, L::Foreground);
}

void iconLeftRight(Painter& p, Icon which, float x, float y, float progress, float width) {
    if (progress <= 0) return;
    auto const& art = artOf(which);
    p.pixels(cropped(art, 0, art.height(), static_cast<int>(width * progress)), x, y, 1, L::Foreground);
}

void bevel(Painter& p, Rect const& r, Color topLeft, Color fill, Color bottomRight, Painter::Layer layer) {
    p.fillRect(r, fill, layer);
    p.fillRect({r.x, r.y, r.w - 1, 1}, topLeft, layer);
    p.fillRect({r.x, r.y, 1, r.h - 1}, topLeft, layer);
    p.fillRect({r.x + 1, r.bottom() - 1, r.w - 1, 1}, bottomRight, layer);
    p.fillRect({r.right() - 1, r.y + 1, 1, r.h - 1}, bottomRight, layer);
}

